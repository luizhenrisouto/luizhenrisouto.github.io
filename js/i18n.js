const LANG_HTML = { pt: "pt-BR", en: "en" };

/** Idioma salvo vence; senão, PT para navegador em português ou sem idioma, EN para os demais. */
export function escolherLingua(salva, navegador) {
  if (salva === "pt" || salva === "en") return salva;
  if (!navegador) return "pt";
  return navegador.toLowerCase().startsWith("pt") ? "pt" : "en";
}

/** Aplica os textos do idioma na página: data-i18n, lang e botões. */
export function aplicarTextos(doc, lingua) {
  const textos = TEXTOS[lingua];
  for (const el of doc.querySelectorAll("[data-i18n]")) {
    const texto = textos[el.dataset.i18n];
    if (texto) el.textContent = texto;
  }
  doc.documentElement.lang = LANG_HTML[lingua];
  for (const b of doc.querySelectorAll("button[data-lingua]")) b.setAttribute("aria-pressed", String(b.dataset.lingua === lingua));
}
